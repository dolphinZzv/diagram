const dicts: Record<Lang, Dict> = { zh, en };

function detectLang(): Lang {
  if (typeof window === "undefined") return "zh";
  try {
    const saved = localStorage.getItem("diagram_lang");
    if (saved === "zh" || saved === "en") return saved;
  } catch {
    /* ignore */
  }
  return (navigator.language || "").toLowerCase().startsWith("zh") ? "zh" : "en";
}

interface I18nState {
  lang: Lang;
  setLang: (l: Lang) => void;
}

export const useI18n = create<I18nState>((set) => ({
  lang: detectLang(),
  setLang: (lang) => {
    try {
      localStorage.setItem("diagram_lang", lang);
    } catch {
      /* ignore */
    }
    set({ lang });
  },
}));

export function translate(lang: Lang, key: string, vars?: Record<string, string | number>): string {
  let s = dicts[lang]?.[key] ?? zh[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      s = s.split(`{${k}}`).join(String(v));
    }
  }
  return s;
}

/** Hook returning a `t(key, vars?)` function bound to the current language. */
export function useT() {
  const lang = useI18n((s) => s.lang);
  return useCallback(
    (key: string, vars?: Record<string, string | number>) => translate(lang, key, vars),
    [lang]
  );
}

export { detectLang };

/** Translate using the current language (for non-React code, e.g. the store). */
export function tr(key: string, vars?: Record<string, string | number>): string {
  return translate(useI18n.getState().lang, key, vars);
}

/** Label used for a freshly added shape (localized shape name). */
export function defaultShapeLabel(shape: string): string {
  return translate(useI18n.getState().lang, `shape.${shape}`);
}
